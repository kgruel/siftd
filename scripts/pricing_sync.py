#!/usr/bin/env python3
"""Refresh src/siftd/data/pricing.toml from models.dev.

Scope: models under the models.dev providers ``anthropic``, ``openai`` and
``google`` whose ``cost`` has numeric ``input`` and ``output``, not both zero. Each upstream id is
canonicalized with ``siftd.model_names.parse_model_name`` (the function ingest uses),
so dated aliases and ``-preview`` ids land on the name responses are stored under.

Ownership, per ``(model, provider)`` entry in the file:

- ``pinned = true``: never modified, text included (comments survive). A disagreement
  with upstream is reported, comparing effective rates (a cache field the entry omits
  is compared at the rate the runtime derives for it).
- other entries under anthropic/openai/google: owned by the sync. Rewritten from
  upstream; ``as_of`` moves to the run date only when an effective price changed (or the
  entry is new), so a second run is a no-op.
- entries under any other provider: kept verbatim, text included.
- owned entries no longer listed upstream: kept (old logs still need a price) and
  reported.

The file is split at a marker line. Everything above it is hand-written header
documentation and is preserved; everything below it is regenerated, grouped by
provider, sorted by model. Verbatim entries keep their own leading comments and body
text; the regenerated section headers are the only lines the sync drops. Stdlib plus
``siftd.model_names`` only.

Exit codes: 0 ok; 1 with ``--check`` when the file would change; 2 on error
(fetch or parse failure, alias collapse conflict, missing marker line).

Usage:
    ./dev pricing-sync [--check] [--from FILE] [--as-of YYYY-MM-DD] [--target PATH]
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import math
import re
import sys
import tomllib
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from pathlib import Path

from siftd.model_names import parse_model_name

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_TARGET = REPO_ROOT / "src" / "siftd" / "data" / "pricing.toml"
MODELS_DEV_URL = "https://models.dev/api.json"
SOURCE = MODELS_DEV_URL

OWNED_PROVIDERS = ("anthropic", "openai", "google")
PRICE_FIELDS = ("input_per_mtok", "output_per_mtok", "cache_read_per_mtok", "cache_creation_per_mtok")
_KEY_ORDER = ("model", "provider", "pinned", *PRICE_FIELDS, "source", "as_of")

MARKER = "# --- generated by ./dev pricing-sync: everything below this line is rewritten ---"
_SECTION_LINE = re.compile(r"^# ─── .+ ───$")

# An omitted cache rate is derived at cost time, as storage/sql_helpers.py does:
# COALESCE(cache_read_per_mtok, input * 0.1) and COALESCE(cache_creation_per_mtok, input * 1.25).
# test_pricing_sync.py asserts these literals still appear in that SQL.
CACHE_READ_MULTIPLE = 0.1
CACHE_CREATION_MULTIPLE = 1.25


class SyncError(Exception):
    """A condition the sync refuses to paper over. Maps to exit code 2."""


@dataclass(frozen=True)
class Upstream:
    """One canonical model, chosen from the upstream ids that collapse onto it."""

    id: str
    provider: str
    canonical: str
    # (input, output, cache_read, cache_write), cache defaulted to input when unpublished.
    prices: tuple[float, float, float, float]
    tiered: bool


@dataclass
class SyncResult:
    text: str
    added: list[str] = field(default_factory=list)
    # label -> ["field old -> new", ...]; label is "model (provider)".
    changed: dict[str, list[str]] = field(default_factory=dict)
    kept_unlisted: list[str] = field(default_factory=list)
    pin_disagreements: list[str] = field(default_factory=list)
    provenance_rewritten: int = 0
    tiered: int = 0
    modeled: int = 0


def _is_number(value: object) -> bool:
    return isinstance(value, (int, float)) and not isinstance(value, bool)


def _upstream_from_model(provider: str, model_id: str, model: dict) -> Upstream | None:
    cost = model.get("cost") or {}
    inp, out = cost.get("input"), cost.get("output")
    if not (_is_number(inp) and _is_number(out)):
        return None
    if inp == 0 and out == 0:
        # A maker listing 0/0 bills the model some other way (Lyria is priced per
        # song); filing $0 would render it free, and unknown is not free.
        return None
    cache_read = cost.get("cache_read")
    cache_write = cost.get("cache_write")
    return Upstream(
        id=model_id,
        provider=provider,
        canonical=parse_model_name(model_id)["name"],
        prices=(
            float(inp),
            float(out),
            float(cache_read) if _is_number(cache_read) else float(inp),
            float(cache_write) if _is_number(cache_write) else float(inp),
        ),
        tiered=bool(cost.get("tiers")) or bool(cost.get("context_over_200k")),
    )


def _choose(canonical: str, provider: str, candidates: list[Upstream]) -> Upstream:
    """Pick the upstream id that stands for a canonical name.

    The id equal to the canonical name wins. Otherwise identical prices are fine
    (lowest id, for determinism). Otherwise the collapse is ambiguous and refused.
    """
    candidates = sorted(candidates, key=lambda u: u.id)
    for u in candidates:
        if u.id == canonical:
            return u
    first = candidates[0]
    for other in candidates[1:]:
        if other.prices != first.prices:
            raise SyncError(
                f"{canonical} ({provider}): upstream ids {first.id!r} {first.prices} and "
                f"{other.id!r} {other.prices} collapse to one name with different prices, "
                f"and neither equals {canonical!r}"
            )
    return first


def collect_upstream(upstream: dict) -> dict[tuple[str, str], Upstream]:
    """Map ``(model, provider)`` (the pricing.toml key) to the chosen upstream model."""
    groups: dict[tuple[str, str], list[Upstream]] = {}
    for provider in OWNED_PROVIDERS:
        models = (upstream.get(provider) or {}).get("models") or {}
        for model_id, model in models.items():
            u = _upstream_from_model(provider, model_id, model)
            if u is not None:
                groups.setdefault((u.canonical, provider), []).append(u)
    return {key: _choose(key[0], key[1], cands) for key, cands in groups.items()}


def _label(model: str, provider: str) -> str:
    return f"{model} ({provider})"


def _fmt(value: object) -> str:
    return "unset" if value is None else repr(value)


@dataclass(frozen=True)
class _Block:
    """One existing ``[[price]]`` entry kept verbatim: its parsed row and its exact text."""

    row: dict
    # Leading comments (section headers dropped) plus the table; ends with one newline.
    raw: str


def _is_lead(line: str) -> bool:
    """A line that can sit above an entry's header: blank, or a comment."""
    return not line.strip() or line.lstrip().startswith("#")


def _blocks(below: str, rows: list[dict]) -> list[_Block]:
    """Cut the regenerated region into one raw block per ``[[price]]`` table.

    A table's leading run is the blank and comment lines directly above its header,
    back to the previous table's last body line. Each raw block is checked to parse
    back to exactly its own row, so a layout this cut cannot represent fails loudly.
    """
    lines = below.splitlines(keepends=True)
    starts = [i for i, line in enumerate(lines) if line.strip() == "[[price]]"]
    if len(starts) != len(rows):
        raise SyncError("cannot split the regenerated section into entries: unexpected table layout")
    leads = []
    for start in starts:
        i = start
        while i > 0 and _is_lead(lines[i - 1]):
            i -= 1
        leads.append(i)
    ends = leads[1:] + [len(lines)]
    blocks = []
    for row, lo, hi in zip(rows, leads, ends):
        kept = [line for line in lines[lo:hi] if not _SECTION_LINE.match(line.rstrip("\n"))]
        while kept and not kept[0].strip():
            kept.pop(0)
        while kept and not kept[-1].strip():
            kept.pop()
        raw = "".join(kept)
        if not raw.endswith("\n"):
            raw += "\n"
        if tomllib.loads(raw).get("price") != [row]:
            raise SyncError(f"{_label(row['model'], row['provider'])}: entry text cannot be kept verbatim")
        blocks.append(_Block(row=row, raw=raw))
    return blocks


def _split(text: str) -> tuple[str, list[_Block]]:
    """Return (header text, existing entries). The header is everything above MARKER."""
    lines = text.splitlines(keepends=True)
    marks = [i for i, line in enumerate(lines) if line.rstrip("\n") == MARKER]
    if len(marks) != 1:
        raise SyncError(f"pricing.toml must contain exactly one marker line: {MARKER}")
    header = "".join(lines[: marks[0]]).rstrip() + "\n\n"
    below = "".join(lines[marks[0] + 1 :])
    rows = tomllib.loads(below).get("price", [])
    seen: set[tuple[str, str]] = set()
    for row in rows:
        if "model" not in row or "provider" not in row:
            raise SyncError(f"[[price]] entry without model and provider: {row!r}")
        key = (row["model"], row["provider"])
        if key in seen:
            raise SyncError(f"duplicate [[price]] entry for {_label(*key)}")
        seen.add(key)
        if "pinned" in row and not isinstance(row["pinned"], bool):
            raise SyncError(f"{_label(*key)}: pinned must be true or false")
    return header, _blocks(below, rows)


def _is_derived(row: dict, name: str) -> bool:
    """True when the entry omits a cache field, so the runtime derives its rate."""
    return name.startswith("cache") and row.get(name) is None


def _eff(row: dict) -> dict[str, object]:
    """Effective price of each field, as the runtime bills it.

    An omitted cache rate is derived from input exactly as storage/sql_helpers.py does.
    """
    inp = row.get("input_per_mtok")
    read = row.get("cache_read_per_mtok")
    creation = row.get("cache_creation_per_mtok")
    if read is None and _is_number(inp):
        read = inp * CACHE_READ_MULTIPLE
    if creation is None and _is_number(inp):
        creation = inp * CACHE_CREATION_MULTIPLE
    return {
        "input_per_mtok": inp,
        "output_per_mtok": row.get("output_per_mtok"),
        "cache_read_per_mtok": read,
        "cache_creation_per_mtok": creation,
    }


def _same(a: object, b: object) -> bool:
    """Equal prices. Derived floats carry noise (3.0 * 0.1 != 0.3), so compare with tolerance."""
    if _is_number(a) and _is_number(b):
        return math.isclose(a, b, rel_tol=1e-9, abs_tol=1e-12)
    return a == b


def _owned_row(u: Upstream, as_of: str) -> dict:
    inp, out, cache_read, cache_write = u.prices
    return {
        "model": u.canonical,
        "provider": u.provider,
        "input_per_mtok": inp,
        "output_per_mtok": out,
        "cache_read_per_mtok": cache_read,
        "cache_creation_per_mtok": cache_write,
        "source": SOURCE,
        "as_of": as_of,
    }


def sync(existing_text: str, upstream: dict, today: str) -> SyncResult:
    """Pure transform: existing file text + upstream JSON -> new file text and a report."""
    header, existing = _split(existing_text)
    wanted = collect_upstream(upstream)
    result = SyncResult(text="", tiered=sum(u.tiered for u in wanted.values()), modeled=len(wanted))

    # Each value is a verbatim _Block (other providers, pinned) or a row to regenerate.
    rows: dict[tuple[str, str], _Block | dict] = {}
    seen_upstream: set[tuple[str, str]] = set()

    for block in existing:
        row = block.row
        key = (row["model"], row["provider"])
        label = _label(*key)
        if row["provider"] not in OWNED_PROVIDERS:
            rows[key] = block
            continue

        u = wanted.get(key)
        if row.get("pinned") is True:
            rows[key] = block
            if u is None:
                result.kept_unlisted.append(label)
            else:
                seen_upstream.add(key)
                eff = _eff(row)
                upstream_values = dict(zip(PRICE_FIELDS, u.prices))
                for name in PRICE_FIELDS:
                    if not _same(eff[name], upstream_values[name]):
                        note = " (derived)" if _is_derived(row, name) else ""
                        result.pin_disagreements.append(
                            f"{label}: pinned {name} {eff[name]!r}{note} != upstream {u.id!r} {upstream_values[name]!r}"
                        )
            continue

        if u is None:
            rows[key] = dict(row)
            result.kept_unlisted.append(label)
            continue
        seen_upstream.add(key)

        new = _owned_row(u, today)
        if row.get("source") != SOURCE:
            result.provenance_rewritten += 1
        before = _eff(row)
        changes = [
            f"{name} {_fmt(before[name])} -> {_fmt(new[name])}"
            for name in PRICE_FIELDS
            if not _same(before[name], new[name])
        ]
        if changes:
            result.changed[label] = changes
            as_of = today
        else:
            as_of = row.get("as_of", today)
        rows[key] = _owned_row(u, as_of)

    for key, u in sorted(wanted.items()):
        if key in seen_upstream:
            continue
        result.added.append(f"{_label(*key)} {u.prices[0]!r}/{u.prices[1]!r}")
        rows[key] = _owned_row(u, today)

    result.kept_unlisted.sort()
    result.pin_disagreements.sort()
    result.text = _render(header, rows)
    return result


def _toml_value(value: object) -> str:
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise SyncError(f"non-finite number {value!r} cannot be written")
        return repr(value)
    if isinstance(value, dt.date):
        return json.dumps(value.isoformat())
    raise SyncError(f"unsupported value {value!r} in pricing entry")


def _render_entry(row: dict) -> str:
    lines = ["[[price]]"]
    for key in [k for k in _KEY_ORDER if k in row] + sorted(k for k in row if k not in _KEY_ORDER):
        lines.append(f"{key} = {_toml_value(row[key])}")
    return "\n".join(lines) + "\n"


def _entry_text(payload: _Block | dict) -> str:
    return payload.raw if isinstance(payload, _Block) else _render_entry(payload)


def _render(header: str, rows: dict[tuple[str, str], _Block | dict]) -> str:
    by_provider: dict[str, list[tuple[str, _Block | dict]]] = {}
    for (model, provider), payload in rows.items():
        by_provider.setdefault(provider, []).append((model, payload))
    order = [p for p in OWNED_PROVIDERS if p in by_provider]
    order += sorted(p for p in by_provider if p not in OWNED_PROVIDERS)
    blocks = []
    for provider in order:
        group = sorted(by_provider[provider], key=lambda item: item[0])
        blocks.append(f"# ─── {provider} ───\n" + "\n".join(_entry_text(payload) for _, payload in group))
    return header + MARKER + "\n\n" + "\n\n".join(blocks)


def format_report(result: SyncResult, check: bool, changed_file: bool) -> str:
    out = [
        f"upstream models in scope (after alias collapse): {result.modeled}",
        f"added ({len(result.added)}):",
        *(f"  {line}" for line in result.added),
        f"changed ({len(result.changed)}):",
        *(f"  {label}: {'; '.join(changes)}" for label, changes in sorted(result.changed.items())),
        f"kept, no longer listed upstream ({len(result.kept_unlisted)}):",
        *(f"  {label}" for label in result.kept_unlisted),
        f"pin disagreements ({len(result.pin_disagreements)}):",
        *(f"  {line}" for line in result.pin_disagreements),
        f"provenance rewritten to {SOURCE} without a price change: {result.provenance_rewritten}",
        f"tiered upstream models (base rate written, tiers not modeled): {result.tiered} of {result.modeled}",
    ]
    if check:
        out.append("file would change; run ./dev pricing-sync" if changed_file else "file is current")
    else:
        out.append("file changed" if changed_file else "file unchanged")
    return "\n".join(out)


def load_upstream(source: str | None) -> dict:
    if source is not None:
        try:
            data = json.loads(Path(source).read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise SyncError(f"cannot read {source}: {exc}") from exc
    else:
        request = urllib.request.Request(MODELS_DEV_URL, headers={"User-Agent": "siftd-pricing-sync"})
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                data = json.loads(response.read().decode("utf-8"))
        except (OSError, urllib.error.URLError, json.JSONDecodeError) as exc:
            raise SyncError(f"cannot fetch {MODELS_DEV_URL}: {exc} (retry, or use --from FILE)") from exc
    if not isinstance(data, dict):
        raise SyncError("upstream JSON is not an object keyed by provider id")
    return data


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Refresh src/siftd/data/pricing.toml from models.dev.")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 if the file would change")
    parser.add_argument("--from", dest="from_file", metavar="FILE", help="read a local models.dev JSON copy")
    parser.add_argument("--as-of", metavar="YYYY-MM-DD", help="run date to stamp changed entries (default: today)")
    parser.add_argument("--target", metavar="PATH", default=str(DEFAULT_TARGET), help="pricing file to sync")
    args = parser.parse_args(argv)

    try:
        today = dt.date.fromisoformat(args.as_of).isoformat() if args.as_of else dt.date.today().isoformat()
        target = Path(args.target)
        existing_text = target.read_text(encoding="utf-8")
        result = sync(existing_text, load_upstream(args.from_file), today)
    except (SyncError, ValueError) as exc:
        print(f"pricing-sync: {exc}", file=sys.stderr)
        return 2

    changed_file = result.text != existing_text
    print(format_report(result, args.check, changed_file))
    if args.check:
        return 1 if changed_file else 0
    if changed_file:
        target.write_text(result.text, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
